"""Generates golden_payloads.h from tests/golden/{hello,telem}.hex, for use by main.cpp.
Run after any protocol change that touches hello.hex/telem.hex:

    python tools/espnow_beacon/gen_golden_arrays.py
"""
from pathlib import Path

GOLDEN_DIR = Path(__file__).parent.parent.parent / "tests" / "golden"
OUT = Path(__file__).parent / "include" / "golden_payloads.h"


def _array(name: str, hex_file: str) -> str:
    data = bytes.fromhex((GOLDEN_DIR / hex_file).read_text().strip())
    body = ", ".join(f"0x{b:02X}" for b in data)
    return f"static const uint8_t {name}[] = {{{body}}};\nstatic const size_t {name}_LEN = {len(data)};\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = (
        "// golden_payloads.h -- GENERATED by tools/espnow_beacon/gen_golden_arrays.py\n"
        "// from tests/golden/hello.hex and telem.hex. Do not edit by hand.\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
        + _array("HELLO_GOLDEN", "hello.hex")
        + "\n"
        + _array("TELEM_GOLDEN", "telem.hex")
    )
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
